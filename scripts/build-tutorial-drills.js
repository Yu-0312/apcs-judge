#!/usr/bin/env node
'use strict';

// Build the small code-reading shard used by tutorial.html. The full reading
// bank remains the source of truth; the tutorial needs only a representative
// pool for its three-question chapter drills.
const fs = require('fs');
const path = require('path');
const vm = require('vm');

const ROOT = path.join(__dirname, '..');
const sourcePath = path.join(ROOT, 'data', 'reading-questions.js');
const outputPath = path.join(ROOT, 'data', 'tutorial-reading-drills.js');
const source = fs.readFileSync(sourcePath, 'utf8');
const questions = vm.runInNewContext(source + '\n;READING_QUESTIONS', {}, { filename: sourcePath, timeout: 30000 });

const LANGS = ['python', 'cpp', 'c', 'java'];
const CATS = ['基礎', '流程', '陣列字串', '結構類別', '演算法', '函式遞迴'];
const PER_GROUP = 12;
const selected = new Map();

function evenlySample(items, limit) {
  if (items.length <= limit) return items.slice();
  const out = [];
  for (let i = 0; i < limit; i++) out.push(items[Math.floor(i * (items.length - 1) / (limit - 1))]);
  return out;
}

for (const lang of LANGS) {
  for (const cat of CATS) {
    const candidates = questions.filter(q => {
      const fallbackC = (lang === 'cpp' || lang === 'java') && q.lang === 'c' && (cat === '基礎' || cat === '流程');
      return q && Array.isArray(q.options) && q.options.length === 4 && q.cat === cat && (!q.lang || q.lang === lang || fallbackC);
    });
    if (candidates.length < 3) throw new Error(`Not enough tutorial drills for ${lang}/${cat}: ${candidates.length}`);
    evenlySample(candidates, PER_GROUP).forEach(q => selected.set(q.id, q));
  }
}

const fields = ['id', 'exam', 'num', 'topic', 'lang', 'level', 'cat', 'code', 'q', 'options', 'answer', 'explain'];
const shard = questions.filter(q => selected.has(q.id)).map(q => {
  const out = {};
  fields.forEach(key => { if (q[key] !== undefined) out[key] = q[key]; });
  return out;
});
const banner = '// Generated by scripts/build-tutorial-drills.js from reading-questions.js.\n';
const generated = banner + 'const TUTORIAL_READING_QUESTIONS = ' + JSON.stringify(shard) + ';\n';
if (process.argv.includes('--check')) {
  const existing = fs.existsSync(outputPath) ? fs.readFileSync(outputPath, 'utf8') : '';
  if (existing !== generated) {
    console.error(`${path.relative(ROOT, outputPath)} is stale; run node scripts/build-tutorial-drills.js`);
    process.exit(1);
  }
  console.log(`${path.relative(ROOT, outputPath)} is current: ${shard.length} questions, ${Buffer.byteLength(generated)} bytes`);
} else {
  fs.writeFileSync(outputPath, generated);
  console.log(`Wrote ${path.relative(ROOT, outputPath)}: ${shard.length} questions, ${Buffer.byteLength(generated)} bytes`);
}
